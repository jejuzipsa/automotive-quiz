"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),"utf8"));
const changes=read("data/qa/technical-qa9-changes.json");
const required=["auto-made-r01-s03-q02","auto-made-r01-s03-q03","auto-made-r01-s03-q06","auto-made-r01-s04-q17"];
assert.deepEqual(changes.map(x=>x.id).sort(),required.sort());
const qs={electrical:read("data/past/drafts/electrical.json"),eco:read("data/past/drafts/eco.json")};
const es={electrical:read("data/explanations/drafts/electrical.json"),eco:read("data/explanations/drafts/eco.json")};
const qa7=new Map(read("data/qa/technical-qa7-electrical-r01-option-audit.json").map(x=>[x.id,x]));
const qa8=new Map(read("data/qa/technical-qa8-eco-r01-option-audit.json").map(x=>[x.id,x]));
for(const c of changes){
 const q=qs[c.subject].find(x=>x.id===c.id);
 const e=es[c.subject].find(x=>x.id===c.id);
 const history=(c.subject==="eco"?qa8:qa7).get(c.id);
 assert.ok(q&&e&&history,c.id);
 assert.equal(c.before.question,history.question_at_review);
 assert.deepEqual(c.before.choices,history.options.map(x=>x.text));
 assert.equal(c.before.answer,history.correct_number);
 assert.equal(c.before.correct_choice,history.correct_choice);
 assert.equal(c.before.answer,c.after.answer,"original answer slot must not change");
 assert.equal(q.question,c.after.question);
 assert.deepEqual(q.choices,c.after.choices);
 assert.equal(e.reason,c.after.reason);
 assert.equal(e.key_point,c.after.key_point);
 assert.equal(q.answer,e.correct_answer);
 assert.equal(q.choices[q.answer-1],e.correct_choice);
 assert.equal(q.editorial_revision,"qa9_editorial_repair");
 assert.equal(e.editorial_revision,"qa9_editorial_repair");
 assert.equal(q.qa9_revision.status,"editorial_revised_pending_new_option_review");
 assert.equal(e.qa9_revision.status,"editorial_revised_pending_new_option_review");
 assert.equal(q.qa9_revision.technical_final_approval,false);
 assert.equal(q.qa9_revision.web_publication,false);
 assert.equal(q.publishable,false);
 assert.equal(q.technical_answer_status,"pending_independent_review");
 assert.equal(e.technical_answer_status,"pending_independent_review");
 assert.ok(c.evidence_urls.length>0);
 const prior=c.subject==="eco"?"qa8":"qa7";
 assert.equal(q["technical_verification_"+prior],undefined,"stale first-pass validation must be cleared");
 assert.equal(e["technical_verification_"+prior],undefined);
 assert.equal(e["option_analysis_"+prior],undefined);
}
const q2=qs.electrical[1],q3=qs.electrical[2],q6=qs.electrical[5],eco17=qs.eco[16];
assert.match(q2.question,/100BASE-T1/);
assert.match(q2.choices[q2.answer-1],/단일 트위스트페어/);
assert.match(q3.choices[q3.answer-1],/60Ω/);
assert.match(q6.choices[q6.answer-1],/전압강하/);
assert.match(eco17.choices[eco17.answer-1],/서로 다른 회전속도/);
assert.equal(read("data/manifest.json").banks.some(x=>x.file.includes("/drafts/")),false);
console.log("PASS QA9: four real editorial fixes with previous QA7/QA8 evidence snapshots; new variants need review; no publication.");
