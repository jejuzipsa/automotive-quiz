"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const root=process.env.AUTO_QUIZ_REPO||path.resolve(__dirname,"..");
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),"utf8"));
const ledger=read("data/qa/technical-qa42-eco-scope-replacements.json");
assert.equal(ledger.length,15);assert.equal(new Set(ledger.map(x=>x.id)).size,15);
assert.deepEqual([4,5,6].map(r=>ledger.filter(x=>x.round===r).length),[5,5,5]);
assert.deepEqual([4,5,6].map(r=>ledger.filter(x=>x.round===r).map(x=>x.question_number)),[[5,12,13,14,15],[5,12,13,14,15],[5,12,13,14,15]]);
const origAnswer={4:{5:4,12:2,13:1,14:3,15:4},5:{5:3,12:3,13:4,14:4,15:2},6:{5:1,12:2,13:3,14:1,15:2}};
let count=0;
for(const row of ledger){
 const prefix="round"+String(row.round).padStart(2,"0");
 const q=read("data/past/drafts/"+prefix+"/eco.json")[row.question_number-1];
 const e=read("data/explanations/drafts/"+prefix+"/eco.json")[row.question_number-1];
 const qa={4:18,5:22,6:25}[row.round];
 const audit=read("data/qa/technical-qa"+qa+"-r"+String(row.round).padStart(2,"0")+"-eco-option-audit.json")[row.question_number-1];
 const key="option_analysis_qa"+qa;
 assert.equal(q.id,row.id);assert.equal(e.id,row.id);
 assert.equal(q.round,row.round);assert.equal(q.subject,"eco");assert.equal(q.question_number,row.question_number);
 assert.equal(q.question,row.after.question);assert.notEqual(q.question,row.before.question);
 assert.deepEqual(q.choices,row.after.choices);
 assert.equal(q.answer,row.before.answer);assert.equal(q.answer,row.after.answer);
 assert.equal(q.answer,origAnswer[row.round][row.question_number]);
 assert.equal(e.correct_answer,q.answer);assert.equal(e.correct_choice,q.choices[q.answer-1]);
 assert.equal(e.reason,row.after.reason);assert.equal(e.key_point,row.after.key_point);
 assert.deepEqual(e[key],row.after.option_analysis);
 assert.deepEqual(e.option_analysis_qa42,row.after.option_analysis);
 assert.equal(audit.question_at_review,row.before.question);
 assert.deepEqual(audit.options.map(o=>o.text),row.before.choices);
 assert.equal(audit.correct_choice,row.before.correct_choice);
 assert.deepEqual(q["technical_verification_qa"+qa].source_urls,row.after.reference_urls);
 assert.deepEqual(e["technical_verification_qa"+qa].source_urls,row.after.reference_urls);
 assert.deepEqual(e.reference_urls,row.after.reference_urls);
 assert.equal(q.qa42_editorial_replacement.new_independently_authored_eco_study_question_not_exam_original,true);
 assert.equal(e.qa42_editorial_replacement.technical_final_approval,false);
 assert.equal(q.qa42_editorial_replacement.web_publication,false);
 assert.equal(q.subject_classification_review.status,"hold_do_not_publish");
 assert.equal(e.subject_classification_review.status,"hold_do_not_publish");
 assert.equal(q.subject_classification_review.qa42_current_question_may_now_fit_eco,true);
 assert.equal(q.publishable,false);assert.equal(q.review_status,"editorial_draft");
 assert.equal(q.technical_answer_status,"pending_independent_review");
 assert.equal(e.technical_answer_status,"pending_independent_review");
 assert.ok(row.after.reference_urls.length>=1);
 for(let i=0;i<4;i++){
  const opt=e[key][i];assert.equal(opt.number,i+1);assert.equal(opt.text,q.choices[i]);
  assert.equal(opt.verdict,i+1===q.answer?"correct":"incorrect");assert.ok(opt.rationale.length>=20);
  count++;
 }
}
assert.equal(count,60);
const m=read("data/manifest.json");assert.ok(m.banks.every(b=>!b.file.includes("/drafts/")));
assert.equal(m.banks.filter(b=>b.track==="expected").reduce((s,b)=>s+b.count,0),80);
const st=read("data/bank-status.json").technical_qa42;
assert.equal(st.reauthored_eco_items,15);
assert.equal(st.historical_subject_holds_retained,55);
assert.equal(st.remaining_provisional_cross_subject_candidates,18);
assert.equal(st.remaining_overlap_candidates,3);
assert.equal(st.legacy_false_positive_candidates,1);
assert.equal(st.independent_final_technical_approvals,0);
assert.equal(st.published_past_reconstructed_items,0);
console.log("PASS QA42: 15/60 eco new-option mappings, historical QA18/22/25 audits intact, 55 holds, zero independent approvals/publications.");
